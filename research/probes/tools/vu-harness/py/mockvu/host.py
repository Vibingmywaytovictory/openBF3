"""Mock VU host (DESIGN.md 13.2): one lupa.lua54 runtime per realm, the mod loaded into each in a VU-like sandbox, the
clock advanced in chunks of ticks inside Lua, VU-format log files, NetEvents bridged between the realms (one tick
latency), the scripted user's snapshots replayed as client frames, and the runtime observe-only checks collected.

Nothing here touches VU or the BF3 install: the mod sources are read from mod/mharness, logs go to a scratch folder.
"""

import json
import os
import random
import re

import lupa.lua54 as lua54

from . import laws as LAWS
from . import levels as LEVELS

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
LUA_DIR = os.path.join(HERE, 'lua')
MOD_DIR = os.path.join(ROOT, 'mod', 'mharness')
INV_PATH = os.path.join(ROOT, 'schema', 'api_inventory.json')

SERVER_FILES = ['vu_core.lua', 'vu_math.lua', 'vu_world.lua', 'vu_soldier.lua', 'vu_weapons.lua', 'vu_conquest.lua',
                'vu_server.lua', 'vu_user.lua']
CLIENT_FILES = ['vu_core.lua', 'vu_math.lua', 'vu_world.lua', 'vu_client.lua']
HEADER = ['[21:00:00.000] [info] Initializing Venice Unleashed Server (Build 20682)',
          '[21:00:00.000] [info] VeniceEXT engine v1.15.0']
CLIENT_HEADER = ['[21:00:00.000] [info] Venice Unleashed Client (Build 20682)',
                 '[21:00:00.000] [info] VeniceEXT engine v1.15.0']
RE_MH1 = re.compile(r'MH1 (\{.*\})\s*$')
KEEP_E = ('prompt', 'mark', 'p0', 'cmd', 'site', 'fx', 'err', 'census', 'meta', 'ev', 'dmg', 'fov', 'trunc', 'lim')
_INV = None


def inventory():
    global _INV
    if _INV is None:
        with open(INV_PATH, encoding='utf-8') as f:
            _INV = json.load(f)
    return _INV


def mod_sources(mod_dir=MOD_DIR):
    """{'shared/x': src, 'server/y': src, 'client/z': src} for every .lua under mod/ext (mh_cert excluded)."""
    ext = os.path.join(mod_dir, 'ext')
    out = {}
    for realm in ('shared', 'server', 'client'):
        for dirpath, _dirs, files in os.walk(os.path.join(ext, realm)):
            for fn in sorted(files):
                if not fn.endswith('.lua') or fn == 'mh_cert.lua':
                    continue
                full = os.path.join(dirpath, fn)
                rel = os.path.relpath(full, ext).replace(os.sep, '/')
                with open(full, encoding='utf-8') as f:
                    out[rel[:-4]] = f.read()
    return out


def cert_source(ids, gate='mock'):
    items = ', '.join("['%s'] = true" % i for i in sorted(ids))
    return "-- GENERATED by mockrun.py (ignored by git)\nreturn { gate = '%s', ids = { %s } }\n" % (gate, items)


def to_lua(rt, v, depth=0):
    if depth > 40:
        raise ValueError('to_lua: too deep')
    if isinstance(v, dict):
        return rt.table_from({k: to_lua(rt, x, depth + 1) for k, x in v.items() if x is not None})
    if isinstance(v, (list, tuple)):
        return rt.table_from([to_lua(rt, x, depth + 1) for x in v])
    return v


def to_py(v, depth=0):
    if lua54.lua_type(v) != 'table':
        return v
    if depth > 40:
        raise ValueError('to_py: too deep')
    items = list(v.items())
    n = len(items)
    if n and all(isinstance(k, int) for k, _ in items) and sorted(k for k, _ in items) == list(range(1, n + 1)):
        return [to_py(v[i], depth + 1) for i in range(1, n + 1)]
    return {k: to_py(x, depth + 1) for k, x in items}


class Realm(object):
    def __init__(self, name, files, laws, hz, seed):
        self.name = name
        self.rt = lua54.LuaRuntime(register_eval=False, register_builtins=False, unpack_returned_tuples=True)
        g = self.rt.globals()
        for fn in files:
            with open(os.path.join(LUA_DIR, fn), encoding='utf-8') as f:
                src = f.read()
            chunk = g.load(src, '@mock/' + fn, 't')
            if isinstance(chunk, tuple) or chunk is None:
                raise RuntimeError('mock %s: %s' % (fn, chunk))
            chunk()
        self.mock = g.mock
        m = self.mock
        m.realm = name
        m.laws = to_lua(self.rt, {k: v for k, v in laws.items() if not isinstance(v, (list, tuple))})
        m.member_missing = laws.get('member_missing', 'raise')
        inv = inventory()
        m.load_inventory(to_lua(self.rt, {'entries': inv['entries'], 'inherits': inv['inherits'],
                                          'bot_assign': inv['bot_assign'], 'fixture_calls': inv['fixture_calls'],
                                          'rcon_read_whitelist': inv['rcon_read_whitelist']}))
        for e in inv['entries']:
            if e['realm'] in (name, 'shared'):
                if e['kind'] == 'event':
                    m.EVENT_OK[e['sym']] = True
                elif e['kind'] == 'hook':
                    m.HOOK_OK[e['sym']] = True
        m.hz = hz
        m.dt = 1.0 / hz
        m.wall0 = 75600
        m.rng_world = m.rng(seed)

    def table(self, v):
        return to_lua(self.rt, v)


class Host(object):
    """One mock VU server + client with the mod loaded. chunk(n) advances n ticks; logs are written as they come."""

    def __init__(self, laws=None, seed=1, outdir=None, cert=None, coverage=False, mod_dir=MOD_DIR, tag='run',
                 level_opts=None):
        self.laws = LAWS.make(**(laws or {}))
        self.seed = seed
        self.hz = int(self.laws['hz'])
        self.outdir = outdir
        self.coverage = coverage
        lw = dict(self.laws)
        if lw.get('tcost') is not None:
            tc = lw['tcost']
            if isinstance(tc, str):
                a, b, c = (float(x) for x in tc.split('/'))
                tc = {'spawn': a, 'kill': b, 'remove': c}
            lw['tcost'] = tc
        else:
            lw.pop('tcost', None)
        self.lw = lw
        sources = mod_sources(mod_dir)
        if cert is not None:
            sources['shared/mh_cert'] = cert_source(cert)
        self.sources = sources
        order = ['__shared/__init__', '__init__']
        if self.laws['init_order'] == 'realm_first':
            order = order[::-1]
        self.order = order
        # server
        self.srv = Realm('server', SERVER_FILES, lw, self.hz, seed)
        m = self.srv.mock
        if isinstance(lw.get('tcost'), dict):
            m.laws.tcost = self.srv.table(lw['tcost'])
        self.level_list = LEVELS.levels(origin=self.laws.get('origin'), range_len=self.laws.get('range_len'))
        m.levels = self.srv.table(self.level_list)
        lo = {'preround': bool(self.laws['preround'])}
        lo.update(level_opts or {})
        m.level_opts = self.srv.table(lo)
        ssrc = {k: v for k, v in sources.items() if k.startswith(('shared/', 'server/'))}
        if coverage:
            m.coverage_on()
        self.load_errors = int(m.start_mod(self.srv.table(ssrc), self.srv.table(order), self.laws['vm']))
        m.load_level(1, True)
        # client
        self.cli = Realm('client', CLIENT_FILES, lw, self.hz, seed + 1)
        c = self.cli.mock
        csrc = {k: v for k, v in sources.items() if k.startswith(('shared/', 'client/'))}
        if coverage:
            c.coverage_on()
        self.load_errors += int(c.start_mod(self.cli.table(csrc), self.cli.table(order), self.laws['vm']))
        # outputs
        self.rows = []          # kept rows (e in KEEP_E) from both realms, parsed
        self.inbox = []         # (k, pid, text, yell)
        self.say = []           # client 'chat:' lines
        self.viol = []
        self.errors = []
        self.marks = []
        self.ulog = []
        self.lines_out = 0
        self.max_players = 0
        self.k = 0
        self.local_pid = -1
        self.level_name = self.level_list[0]['name']
        self.rnd = random.Random(seed * 7919 + 13)
        self.slog = self.clog = None
        if outdir:
            os.makedirs(os.path.join(outdir, 'instance', 'logs'), exist_ok=True)
            os.makedirs(os.path.join(outdir, 'client'), exist_ok=True)
            self.slog_path = os.path.join(outdir, 'instance', 'logs', 'vu_2026-10-16_21-00-00_%s.log' % tag)
            self.clog_path = os.path.join(outdir, 'client', 'vu_client_2026-10-16_%s.log' % tag)
            self.slog = open(self.slog_path, 'w', encoding='utf-8', newline='\n')
            self.clog = open(self.clog_path, 'w', encoding='utf-8', newline='\n')
            self.slog.write('\n'.join(HEADER) + '\n')
            self.clog.write('\n'.join(CLIENT_HEADER) + '\n')
        self.drain()

    # -- log writing ---------------------------------------------------------------------------------------------
    def _write(self, f, text):
        lim = int(self.laws['print_limit'] or 0)
        if self.laws['log_drop'] and self.rnd.random() < float(self.laws['log_drop']):
            return
        if lim and len(text) > lim:
            text = text[:lim]
        f.write(text + '\n')
        if self.laws['log_garbage'] and self.rnd.random() < float(self.laws['log_garbage']):
            f.write('[21:00:00.000] [info] [VeniceEXT] [mharness] MH1 {"v":1,"run":NaN,"q":\n')
            f.write('\x00\x01 garbage \xff line\n')

    def _lines(self, out, f, realm):
        for i in range(1, len(out) + 1):
            item = out[i]
            text = item[2]
            if f is not None:
                self._write(f, text)
            self.lines_out += 1
            m = RE_MH1.search(text)
            if m:
                body = m.group(1)
                e = re.search(r'"e":"([a-z0-9]+)"', body)
                if e and e.group(1) in KEEP_E:
                    try:
                        self.rows.append(json.loads(body))
                    except ValueError:
                        pass
            elif realm == 'C' and 'mharness: chat: ' in text:
                self.say.append(text.split('mharness: chat: ', 1)[1])

    # -- the loop --------------------------------------------------------------------------------------------------
    def drain(self):
        m, c = self.srv.mock, self.cli.mock
        self._lines(m.take_out(), self.slog, 'S')
        ib = m.take_inbox()
        for i in range(1, len(ib) + 1):
            x = ib[i]
            self.inbox.append((x[1], x[2], x[3], x[4]))
        for v in to_py(m.take_viol()) or []:
            self.viol.append('server ' + v)
        for v in to_py(m.take_errors()) or []:
            self.errors.append('server ' + v)
        mk = to_py(m.take_marks()) or []
        for k, what in mk:
            self.marks.append((k, what))
            if what.startswith('level-loaded '):
                self.level_name = what.split(' ', 1)[1]
                if self.local_pid >= 0:
                    self.cli.mock.level_loaded(self.level_name, self.level_list[0]['mode'])
        self.ulog.extend(to_py(m.U.take_log()) or [])
        snaps = m.U.take_snaps()
        net = m.take_net()
        events = []
        for i in range(1, len(net) + 1):
            ev = net[i]
            if ev.target == -1 or ev.target == self.local_pid:
                events.append(to_py(ev))
        if self.local_pid >= 0:
            c.frames(self.cli.table(to_py(snaps) or []), self.cli.table(events))
        self._lines(c.take_out(), self.clog, 'C')
        for v in to_py(c.take_errors()) or []:
            self.errors.append('client ' + v)
        cnet = c.take_net()
        for i in range(1, len(cnet) + 1):
            ev = cnet[i]
            if self.local_pid >= 0:
                m.deliver(ev.name, self.local_pid, self.srv.table(to_py(ev.args)))

    def humans(self):
        return 1 if self.local_pid >= 0 else 0

    def chunk(self, n=10):
        m = self.srv.mock
        if self.local_pid < 0 and self.laws['idle_advance'] is False:
            m.idle(n)
            self.k += 0
            return
        m.run_ticks(n)
        self.k = int(m.k)
        self.max_players = max(self.max_players, int(m.U.player_count()))
        self.drain()

    def join(self, team=1):
        pid = int(self.srv.mock.U.join(team))
        self.local_pid = pid
        self.cli.mock.local_pid = pid
        self.cli.mock.level_loaded(self.level_name, self.level_list[0]['mode'])
        return pid

    def leave(self):
        """The human leaves; the leave itself happens in a server tick (Player:Left), even when the empty server
        then idles (idle_advance=False)."""
        m = self.srv.mock
        m.U.leave()
        self.local_pid = -1
        self.cli.mock.local_pid = -1
        m.run_ticks(1)
        self.k = int(m.k)
        self.drain()

    def console(self, text):
        return self.cli.mock.console_cmd(text)

    def stats(self):
        return to_py(self.srv.mock.stats())

    def coverage_data(self):
        out = {}
        for realm in (self.srv, self.cli):
            cov = to_py(realm.mock.cov) or {}
            for src, lines in cov.items():
                s = out.setdefault(src, set())
                if isinstance(lines, dict):
                    s.update(int(k) for k in lines)
                else:
                    s.update(range(1, len(lines) + 1))
        return out

    def close(self):
        for f in (self.slog, self.clog):
            if f is not None:
                f.close()
        self.slog = self.clog = None
        if self.coverage:
            self.srv.mock.coverage_off()
            self.cli.mock.coverage_off()
