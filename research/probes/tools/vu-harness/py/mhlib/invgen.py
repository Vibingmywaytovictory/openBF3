"""Generate ext/server/mh_inventory.lua (the census probe list) from schema/api_inventory.json (DESIGN.md 6.1 P0.2).

The census probes every server/shared method, property and enum value of the inventory for presence. The Lua file is
generated, committed with the mod (VU has no file IO to read the JSON), and check_all.py verifies it is in sync.
"""

import json
import os

HEADER = ('-- GENERATED by py/mhlib/invgen.py from schema/api_inventory.json; do not edit by hand.\n'
          '-- The census (P0.2) probes each entry for presence (DESIGN.md 6.1). check_all.py verifies it is in sync.\n')


def render(inventory):
    rows = []
    for e in inventory['entries']:
        if e['kind'] in ('method', 'prop', 'enum') and e['realm'] in ('server', 'shared'):
            rows.append((e['kind'], e['sym']))
    rows = sorted(set(rows))
    out = [HEADER, 'local M = {}\n\nM.server = {\n']
    for kind, sym in rows:
        out.append("\t{ '%s', '%s' },\n" % (kind, sym))
    out.append('}\n\nreturn M\n')
    return ''.join(out)


def paths(here):
    inv = os.path.join(here, 'schema', 'api_inventory.json')
    lua = os.path.join(here, 'mod', 'mharness', 'ext', 'server', 'mh_inventory.lua')
    return inv, lua


def generate(here, write=True):
    """Return True if the file on disk equals the rendering (after writing it when write is set)."""
    inv_path, lua_path = paths(here)
    with open(inv_path, encoding='utf-8') as f:
        text = render(json.load(f))
    cur = None
    if os.path.isfile(lua_path):
        with open(lua_path, encoding='utf-8', newline='') as f:
            cur = f.read()
    if cur == text:
        return True
    if write:
        with open(lua_path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
    return False
