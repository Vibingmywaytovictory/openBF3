float table_value(const std::array<float, 101> &p_table, float p_x) {
	const float scaled = p_x * 100.0f;
	const int index = static_cast<int>(scaled);
	const float frac = scaled - static_cast<float>(index);
	return frac * p_table[size_t(index) + 1] + (1.0f - frac) * p_table[size_t(index)];
}

