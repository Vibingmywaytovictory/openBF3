float UCConstant::calculate(float) const {
	return value_;
}

float UCLinear::calculate(float p_x) const {
	return std::max(slope_ * p_x + offset_, 0.0f);
}

float UCXInverse::calculate(float p_x) const {
	return std::max(numerator_ / (slope_ * p_x + offset_) + bias_, 0.0f);
}

float SCurve::calculate(float p_x) {
	if (!std::isfinite(p_x)) {
		return 0.0f;
	}
	if (p_x >= 1.0f) {
		return 1.0f;
	}
	if (p_x < 0.0f) {
		return 0.0f;
	}
	return table_value(kSCurveValues, p_x);
}

float JCurve::calculate(float p_x) {
	if (std::isnan(p_x)) {
		return 0.0f;
	}
	if (p_x > 1.0f) {
		return p_x / 100.0f + 1.0f;
	}
	if (p_x < 0.0f) {
		return 0.0f;
	}
	if (p_x == 1.0f) {
		return kJCurveValues[100];
	}
	return table_value(kJCurveValues, p_x);
}

float DecliningSlopeCurve::calculate(float p_x) {
	if (std::isnan(p_x)) {
		return 0.0f;
	}
	if (p_x > 1.0f) {
		return 1.0f;
	}
	if (p_x < 0.0f) {
		return 0.0f;
	}
	if (p_x == 1.0f) {
		return kDecliningSlopeCurveValues[100];
	}
	const float scaled = p_x * 100.0f;
	const int index = static_cast<int>(scaled);
	const float frac = scaled - static_cast<float>(index);
	return (1.0f - frac) * kDecliningSlopeCurveValues[size_t(index)] +
			frac * kDecliningSlopeCurveValues[size_t(index) + 1];
}

